import assert from 'node:assert/strict';
import { createServer } from 'vite';
const testStorage=new Map();
globalThis.localStorage={getItem:key=>testStorage.get(key)??null,setItem:(key,value)=>testStorage.set(key,String(value)),removeItem:key=>testStorage.delete(key),clear:()=>testStorage.clear()};
globalThis.window={localStorage:globalThis.localStorage};
const server=await createServer({configFile:'vite.config.ts',server:{middlewareMode:true},appType:'custom'});
try {
  const {calculateEngineering,RTG_DECAY_PER_YEAR,driveEnergyWh,convertPowerTimeToWh,linkCapacityMbit,slopeAngleDeg}=await server.ssrLoadModule('/src/nasa/engineering.ts');
  const {DEFAULT_CONFIG,INSTRUMENTS,FIXED}=await server.ssrLoadModule('/src/nasa/data.ts');
  const all=calculateEngineering(DEFAULT_CONFIG);
  assert.ok(Math.abs(all.massKg-1025)<.01,'all instruments mass rollup');
  assert.ok(Math.abs(all.genWh-2712.57)<.5,'BOL generation per sol');
  assert.ok(Math.abs(RTG_DECAY_PER_YEAR-.02493)<.00001,'RTG exponential-fit decay');
  assert.ok(Math.abs(all.eNominalWh-2408)<.01,'nominal battery energy Ah × V');
  assert.ok(Math.abs(all.eDeliveredWh-1827.5)<.5,'usable delivered battery energy with reserve and efficiency');
  const subset=calculateEngineering({...DEFAULT_CONFIG,instruments:['mastcam-z','supercam','meda','rimfax']});
  assert.ok(Math.abs(subset.massKg-996.265)<.01,'documented subset mass');
  assert.ok(Math.abs(convertPowerTimeToWh(300,1)-300)<1e-8,'power × time Wh conversion');
  assert.ok(Math.abs(driveEnergyWh(100)-31.86)<.02,'100 m drive energy');
  assert.ok(Math.abs(linkCapacityMbit(2_000_000,480)-960)<1e-8,'UHF link capacity bit/s × seconds');
  assert.ok(Math.abs(slopeAngleDeg(Math.tan(24*Math.PI/180)*2,2)-24)<1e-8,'terrain grade angle uses rise/run correctly');
  assert.ok(slopeAngleDeg(Math.tan(25*Math.PI/180)*2,2)>FIXED.slopeLimitDeg,'grade above documented operational limit is restricted');
  assert.equal(INSTRUMENTS.length,7,'exactly the documented seven selectable instruments');
  assert.equal(FIXED.packs*FIXED.batteryAh*FIXED.voltageV,2408,'SI unit arithmetic');
  const moxie=calculateEngineering({...DEFAULT_CONFIG,moxieRun:true});
  assert.ok(Math.abs(moxie.activityWh-all.activityWh-300)<.01,'MOXIE run energy use');
  assert.ok(moxie.activityWh>all.activityWh,'selection updates calculated load');
  assert.equal(all.issues.length,0,'default configuration flight checks');
  const nonGeology=calculateEngineering({...DEFAULT_CONFIG,instruments:['meda','moxie','rimfax']});
  assert.equal(nonGeology.issues.length,0,'missing geology payload is an operational limitation, not a fabricated NASA hard constraint');
  assert.ok(nonGeology.warnings.some(x=>x.includes('ARES-01 objective design')),'science limitation is disclosed as a game objective rule');
  const extended=calculateEngineering({...DEFAULT_CONFIG,scienceCadence:4});
  assert.equal(extended.activityWh,all.activityWh*4,'extended science cadence scales only the assumed schedule');
  assert.ok(extended.warnings.some(x=>x.includes('energy deficit')),'negative operational energy budget warns but does not hard-block launch');
  assert.ok(calculateEngineering({...DEFAULT_CONFIG,baselineW:901}).issues.some(x=>x.includes('900 W')),'documented 900 W peak is hard validated');
  assert.ok(calculateEngineering({...DEFAULT_CONFIG,instruments:['imaginary']}).issues.some(x=>x.includes('Unsupported')),'unsupported payload selections are rejected');
  const {missionOutcome,createMissionRecord,recoverEvent,scienceRewardForReturnedTargets}=await server.ssrLoadModule('/src/engine/missionFailure.ts');
  const reqs=[{id:'a',name:'A',requiredInstruments:['pixl']}];
  const limitedConfig={...DEFAULT_CONFIG,downlink:'X-band',instruments:['meda','rimfax']};
  const record=createMissionRecord(limitedConfig,calculateEngineering(limitedConfig),reqs);
  assert.ok(record.events.some(x=>x.kind==='instrument-unavailable'),'unsupported science objective creates a disclosed payload limitation');
  const commEvent={id:'c',kind:'communication-backlog',title:'backlog',trigger:'t',explanation:'e',model:'assumed',recoverable:true,status:'active',sol:1};
  assert.equal(recoverEvent([commEvent],'c')[0].status,'recovered','recoverable event transitions to recovered');
  assert.equal(missionOutcome({batteryPercent:90,objectiveCount:1,scannedTargets:['a'],transmittedTargets:['a'],events:[]}), 'full-success','full success requires scanned and returned objectives');
  assert.equal(missionOutcome({batteryPercent:90,objectiveCount:2,scannedTargets:['a'],transmittedTargets:['a'],events:[]}), 'partial-success','returned subset is partial success');
  assert.equal(missionOutcome({batteryPercent:90,objectiveCount:2,scannedTargets:['a'],transmittedTargets:[],events:[]}), 'partial-success','collected but not yet uplinked science avoids a false total-failure classification');
  assert.equal(missionOutcome({batteryPercent:90,objectiveCount:2,scannedTargets:['a'],transmittedTargets:[],events:[commEvent]}), 'recoverable-anomaly','active recoverable anomaly is explicit outcome');
  assert.equal(missionOutcome({batteryPercent:0,objectiveCount:2,scannedTargets:[],transmittedTargets:[],events:[]}), 'mission-failure','empty battery yields mission failure');
  assert.equal(missionOutcome({requested:'abort',batteryPercent:90,objectiveCount:2,scannedTargets:[],transmittedTargets:[],events:[]}), 'mission-abort','player abort is distinct');
  assert.equal(scienceRewardForReturnedTargets(['a'],[{id:'a',reward:25},{id:'b',reward:32}]),25,'only returned science earns campaign reward');
  const {useGameStore}=await server.ssrLoadModule('/src/store/gameStore.ts');
  useGameStore.getState().setRoverConfig({...DEFAULT_CONFIG,instruments:['meda','moxie','rimfax']});
  useGameStore.getState().setMissionPhase('engineering');
  assert.equal(useGameStore.getState().confirmMission(),true,'valid but objective-limited payload may launch with clear warnings');
  useGameStore.getState().setRoverConfig(DEFAULT_CONFIG);
  assert.equal(useGameStore.getState().confirmMission(),true,'valid configuration confirms into launch phase');
  useGameStore.getState().setMissionProgress({x:12,z:-7,battery:81.5,scannedTargets:['ancient-outcrop'],science:25});
  const persisted=JSON.parse(testStorage.get('ares-01-campaign'));
  assert.equal(persisted.state.missionPhase,'launch','confirmed phase persists');
  assert.equal(persisted.state.confirmedMission.results.massKg,1025,'confirmed calculation snapshot persists');
  assert.deepEqual(persisted.state.missionProgress.scannedTargets,['ancient-outcrop'],'mission science progression persists in campaign state');
  assert.equal(persisted.state.missionProgress.battery,81.5,'mission battery reserve persists in campaign state');
  useGameStore.getState().startSurfaceMission();
  assert.ok(useGameStore.getState().missionRecord,'confirmed rover creates a persisted active mission record');
  useGameStore.getState().uplinkResults();
  assert.deepEqual(useGameStore.getState().missionRecord.transmittedTargets,['ancient-outcrop'],'only scanned targets are returned');
  const rpBeforeReturn=useGameStore.getState().agency.rp;
  assert.equal(useGameStore.getState().endMission('complete',81.5),'partial-success','campaign end classifies returned subset');
  assert.equal(useGameStore.getState().missionPhase,'report','campaign routes to report');
  assert.equal(useGameStore.getState().agency.rp,rpBeforeReturn+25,'campaign receives reward only for returned science');
  const finalPersisted=JSON.parse(testStorage.get('ares-01-campaign'));
  assert.equal(finalPersisted.state.missionRecord.outcome,'partial-success','mission outcome persists');
  assert.deepEqual(finalPersisted.state.missionRecord.transmittedTargets,['ancient-outcrop'],'uplink record persists');
  const {useMarsStore}=await server.ssrLoadModule('/src/store/marsStore.ts');
  for (const requested of ['complete', 'abort']) {
    useGameStore.getState().reset();
    useGameStore.getState().confirmMission();
    useGameStore.getState().startSurfaceMission();
    useMarsStore.getState().begin();
    if (requested === 'abort') useMarsStore.getState().togglePause();
    useGameStore.getState().endMission(requested, 80);
    assert.equal(useGameStore.getState().missionPhase, 'report', `${requested} opens report`);
    assert.equal(useMarsStore.getState().phase, 'complete', `${requested} stops surface controls`);
    useGameStore.getState().reset();
    assert.equal(useGameStore.getState().missionPhase, 'briefing', `${requested} restart opens briefing`);
    assert.equal(useMarsStore.getState().phase, 'briefing', `${requested} restart resets surface phase`);
    assert.equal(useMarsStore.getState().battery, 100, `${requested} restart restores battery`);
    assert.equal(useMarsStore.getState().scanningTargetId, null, `${requested} restart clears scans`);
  }
  useGameStore.getState().selectCrew('rihabe');
  assert.equal(useGameStore.getState().selectedCrewId, 'rihabe', 'crew selection is stored');
  assert.equal(JSON.parse(testStorage.get('ares-01-campaign')).state.selectedCrewId, 'rihabe', 'crew selection persists');
  useGameStore.getState().selectCrew('unknown');
  assert.equal(useGameStore.getState().selectedCrewId, 'kavi', 'unknown crew safely falls back');
  useGameStore.getState().selectCrew('houssam');
  useGameStore.getState().reset();
  assert.equal(useGameStore.getState().selectedCrewId, 'kavi', 'new campaign resets selected crew');
  console.log('PASS 60 engineering/campaign checks: NASA equations, constraints, assumptions, outcomes, recovery, rewards and persistence');
} finally { await server.close(); }
